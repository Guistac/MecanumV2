#!/usr/bin/env python3
"""Turns an audio file into a clip for the remote's piezo (SoundClip, lib/RemoteAudio) [D-158]: mono, the end's
silence trimmed, high-pass 300 to 450 Hz (the disc cannot play lower), +6 dB around 2 kHz (where it is loud), a
low-pass above 7 kHz, compressed (ratio 10 above -40 dB, up to +36 dB; an
expander below -45 dB keeps the decays), soft clipped, low-passed again (the clipper's harmonics), 31.25 kHz, 8-bit signed. Writes a
C header with the samples in flash (PROGMEM) and a preview WAV that sounds roughly like the remote will.

    python3 tools/sounds/clip.py tools/sounds/startup.m4a lib/RemoteUi/src/StartupClip.h startupClip [preview.wav] [drive]

drive: how hard the compressed sound is pushed into the clipper (1: a soft clip; 4: heavy, loud, distorted; 20: almost
a square wave, as loud as the timer squares). The disc is quiet: distortion adds the 1 to 4 kHz harmonics it plays
loudest, so loud wins over clean here (2026-10-27).

Needs numpy, and afconvert (macOS) for anything but a 16-bit WAV.
"""
import pathlib
import subprocess
import sys
import tempfile
import wave

import numpy as np

RATE = 31250      #the synth's own rate (Synth::sampleRate): played sample for sample, no interpolation images


def load(path):
    path = pathlib.Path(path)
    with tempfile.TemporaryDirectory() as folder:
        source = path
        if path.suffix.lower() != ".wav":
            source = pathlib.Path(folder) / "source.wav"
            subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16", "-c", "1", str(path), str(source)], check=True)
        w = wave.open(str(source))
        rate = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float) / 32768.0
        if w.getnchannels() > 1:
            x = x.reshape(-1, w.getnchannels()).mean(axis=1)
    return x, rate


def squeeze(x, rate, drive=1.0):
    last = np.nonzero(np.abs(x) > 0.003)[0][-1]
    x = x[:last + int(0.05 * rate)]

    spectrum = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / rate)
    gain = np.clip((f - 300) / 150, 0, 1)
    gain *= 1 + np.clip(1 - np.abs(np.log2(np.maximum(f, 1) / 2000)), 0, 1)
    gain *= np.clip((7500 - f) / 500, 0, 1)
    x = np.fft.irfft(spectrum * gain, len(x))

    window = int(0.010 * rate)
    envelope = np.sqrt(np.convolve(x * x, np.ones(window) / window, mode="same")) + 1e-6
    level = 20 * np.log10(envelope)
    threshold, ratio = -40.0, 10.0
    reduction = np.where(level > threshold, (level - threshold) * (1 - 1 / ratio), 0)
    #below -45 dB an expander turns it down instead of up, so the decays still fade out (not lifted into a flat end)
    reduction += np.where(level < -45.0, (-45.0 - level) * 3.0, 0)
    makeup = min(36.0, -threshold * (1 - 1 / ratio))
    x = x * 10 ** ((makeup - reduction) / 20)

    fade_in, fade_out = int(0.005 * rate), int(0.04 * rate)
    x[:fade_in] *= np.linspace(0, 1, fade_in)
    x[-fade_out:] *= np.linspace(1, 0, fade_out)
    x = x / np.max(np.abs(x))
    x = np.tanh(1.5 * drive * x) / np.tanh(1.5 * drive)

    #the clipper's new harmonics: a low-pass from 4.5 to 5.5 kHz takes off the harsh top (the disc barely plays it)
    #and keeps the resampling below from folding them back down as hiss. Filtering rounds the clipped peaks again, so
    #clip and filter in turn a few times: it settles on a sound both dense (loud) and without the harsh top
    band = np.clip((5500 - f) / 1000, 0, 1)
    for _ in range(4):
        x = np.fft.irfft(np.fft.rfft(x) * band, len(x))
        x = x / np.max(np.abs(x))
        x = np.tanh(2.0 * x) / np.tanh(2.0)
    x = np.fft.irfft(np.fft.rfft(x) * band, len(x))
    x = np.clip(x / np.max(np.abs(x)), -1, 1)

    t = np.arange(int(len(x) * RATE / rate)) * rate / RATE
    y = np.interp(t, np.arange(len(x)), x)
    return np.clip(np.round(y * 127), -127, 127).astype(np.int8)


def write_header(samples, path, name, source, drive):
    lines = [
        "#pragma once",
        "#include <Sound.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "",
        f"//generated by tools/sounds/clip.py from {source} (drive {drive:g}): {len(samples)} samples, "
        f"{len(samples) / RATE:.2f} s at "
        f"{RATE} Hz, 8-bit; do not edit",
        f"static const int8_t {name}Samples[{len(samples)}] PROGMEM = {{",
    ]
    for i in range(0, len(samples), 24):
        lines.append("    " + ", ".join(str(int(v)) for v in samples[i:i + 24]) + ",")
    lines += ["};", f"static const SoundClip {name} = {{{name}Samples, {len(samples)}, {RATE}}};", ""]
    pathlib.Path(path).write_text("\n".join(lines))


def write_preview(samples, path):
    p = wave.open(str(path), "wb")
    p.setnchannels(1)
    p.setsampwidth(2)
    p.setframerate(RATE)
    p.writeframes((samples.astype(np.int16) * 256).tobytes())
    p.close()


if __name__ == "__main__":
    source, header, name = sys.argv[1:4]
    drive = float(sys.argv[5]) if len(sys.argv) > 5 else 1.0
    samples = squeeze(*load(source), drive)
    write_header(samples, header, name, pathlib.Path(source).name, drive)
    if len(sys.argv) > 4:
        write_preview(samples, sys.argv[4])
    rms = np.sqrt(np.mean((samples / 127.0) ** 2))
    print(f"{name}: {len(samples)} samples, {len(samples) / RATE:.2f} s, {len(samples) / 1024:.1f} KB, drive {drive}, "
          f"rms {rms:.2f} (a square: 1.00)")
