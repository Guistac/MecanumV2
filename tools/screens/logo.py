#!/usr/bin/env python3
"""Turns the BERUPO logo picture into lib/RemoteUi/src/BerupoLogo.h: each letter as a 1 bit mask at 4 times the OLED
resolution, placed where it rests on the 128 x 32 screen. The startup animation (RemoteSplash) samples these masks
to draw the letters at any size; at rest it averages 4 x 4 samples per screen pixel.

    python3 tools/screens/logo.py <logo.png>

The picture: the letters in any colour on white. White specks inside a letter (the gloss marks) are filled in, they
are lost at 24 px anyway; the counters of B, R, P and O are larger and stay open.
"""
import pathlib
import sys

import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "lib/RemoteUi/src/BerupoLogo.h"
LETTERS = "BERUPO"
HEIGHT = 24             # letter height on the OLED
TOP = 4                 # rows above the letters
SUPERSAMPLE = 4
SPECK_AREA = 0.002      # white regions inside the letters smaller than this share of the word box are filled


def fill_specks(ink):
    """White regions that do not touch the border and are small: part of the letter."""
    height, width = ink.shape
    seen = np.zeros_like(ink)
    limit = SPECK_AREA * height * width
    for y0 in range(height):
        for x0 in range(width):
            if ink[y0, x0] or seen[y0, x0]:
                continue
            region, stack, border = [], [(y0, x0)], False
            seen[y0, x0] = True
            while stack:
                y, x = stack.pop()
                region.append((y, x))
                border |= y in (0, height - 1) or x in (0, width - 1)
                for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
                    if 0 <= ny < height and 0 <= nx < width and not ink[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        stack.append((ny, nx))
            if not border and len(region) < limit:
                for y, x in region:
                    ink[y, x] = True
    return ink


def main():
    picture = np.array(Image.open(sys.argv[1]).convert("RGB")).astype(int)
    ink = picture.sum(axis=2) < 3 * 200
    rows = np.where(ink.any(axis=1))[0]
    columns = np.where(ink.any(axis=0))[0]
    ink = ink[rows[0]:rows[-1] + 1, columns[0]:columns[-1] + 1]
    ink = np.pad(ink, 2)
    ink = fill_specks(ink)[2:-2, 2:-2]

    high = HEIGHT * SUPERSAMPLE
    wide = round(ink.shape[1] * high / ink.shape[0])
    screenWidth = round(wide / SUPERSAMPLE)
    wide = screenWidth * SUPERSAMPLE
    mask = Image.fromarray((ink * 255).astype(np.uint8)).resize((wide, high), Image.BOX)
    mask = np.array(mask) >= 128
    left = (128 - screenWidth) // 2 * SUPERSAMPLE
    top = TOP * SUPERSAMPLE

    # the letters are the column runs with ink
    used = mask.any(axis=0)
    runs, start = [], None
    for x, value in enumerate(list(used) + [False]):
        if value and start is None:
            start = x
        if not value and start is not None:
            runs.append((start, x))
            start = None
    if len(runs) != len(LETTERS):
        sys.exit(f"found {len(runs)} letters, expected {len(LETTERS)}")

    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"//Generated by tools/screens/logo.py from the BERUPO logo, do not edit. Each letter at {SUPERSAMPLE} times the",
        "//OLED resolution, rows of bits (msb first, rows padded to bytes); x and y place it at rest, in the same units.",
        "namespace BerupoLogo{",
        "",
        f"    static const int16_t supersample = {SUPERSAMPLE};",
        f"    static const int16_t letterCount = {len(LETTERS)};",
        "",
        "    struct Letter{ int16_t x, y, width, height; const uint8_t* bits; };",
        "",
    ]
    letters = []
    for (x0, x1), name in zip(runs, LETTERS):
        part = mask[:, x0:x1]
        used_rows = np.where(part.any(axis=1))[0]
        part = part[used_rows[0]:used_rows[-1] + 1]
        height, width = part.shape
        stride = (width + 7) // 8
        data = []
        for row in part:
            padded = np.concatenate([row, np.zeros(stride * 8 - width, dtype=bool)])
            data += [int("".join("1" if v else "0" for v in padded[i:i + 8]), 2) for i in range(0, stride * 8, 8)]
        lines.append(f"    static const uint8_t bits{name}[] = {{")
        for i in range(0, len(data), 16):
            lines.append("        " + ", ".join(f"0x{v:02X}" for v in data[i:i + 16]) + ",")
        lines.append("    };")
        letters.append(f"        {{{left + x0}, {top + used_rows[0]}, {width}, {height}, bits{name}}},")
    lines += ["", "    static const Letter letters[letterCount] = {"] + letters + ["    };", "};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {screenWidth} x {HEIGHT} px, letters {[r[1] - r[0] for r in runs]} wide at {SUPERSAMPLE}x")


if __name__ == "__main__":
    main()
